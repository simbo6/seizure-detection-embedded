void exfa1_g(const double *x, const int len_x, double* gyr1) {
    int i;

    double x_sort[len_x];			// 绝对值的排序
    for (i = 0; i < len_x; i++) {
        x_sort[i] = fabs(x[i]);
    }

    for (i = 0; i < len_x; i++) {
        (*gyr1) += x_sort[i];		// 绝对值的均�?
    }
    (*gyr1) /= len_x;

}
